const expandedRegenerateEnv = "ASTRO_REGENERATE_FLASH_EXPANDED"

//go:generate env ASTRO_REGENERATE_FLASH_EXPANDED=1 go test -tags astro_lowmem -run=TestExpandedFlashGeneratedFresh -count=1
func TestExpandedFlashGeneratedFresh(t *testing.T) {
	want, err := expandedGenerated()
	if err != nil {
		t.Fatal(err)
	}
	files := map[string][]byte{
		"flash_expanded_generated.go": want.source,
		"expanded_long.bin":           want.long,
		"expanded_modern.bin":         want.modern,
		"expanded_fast.bin":           want.fast,
	}
	if os.Getenv(expandedRegenerateEnv) == "1" {
		for name, data := range files {
			if err := os.WriteFile(name, data, 0o644); err != nil {
				t.Fatal(err)
			}
		}
	}
	for name, data := range files {
		got, err := os.ReadFile(name)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(got, data) {
			t.Fatalf("%s is stale; regenerate with %s=1 go test -tags astro_lowmem -run=%s", name, expandedRegenerateEnv, t.Name())
		}
	}
}

type expandedGeneratedData struct {
	source, long, modern, fast []byte
}

func expandedGenerated() (expandedGeneratedData, error) {
	base, err := ParseFlash(flashLong)
	if err != nil {
		return expandedGeneratedData{}, err
	}
	modern, err := ParseFlash(flashModern)
	if err != nil {
		return expandedGeneratedData{}, err
	}
	fast, err := ParseFlash(flashFast)
	if err != nil {
		return expandedGeneratedData{}, err
	}
	long := buildExpandedTable(base, map[int]bool{3: true})
	modernTable := buildExpandedTable(modern, map[int]bool{3: true})
	fastTable := buildExpandedTable(fast, nil)
	var source bytes.Buffer
	fmt.Fprintln(&source, "//go:build astro_lowmem")
	fmt.Fprintln(&source, "// +build astro_lowmem")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Code generated by flash_expand_test.go; DO NOT EDIT.")
	fmt.Fprintln(&source, "package planets")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "import _ \"embed\"")
	fmt.Fprintln(&source)
	fmt.Fprintf(&source, "const flashExpandedSourceHash = %q\n\n", expandedSourceHash())
	writeEmbeddedTable(&source, "flashExpandedLong", "expanded_long.bin", long.spans)
	writeEmbeddedTable(&source, "flashExpandedModern", "expanded_modern.bin", modernTable.spans)
	writeEmbeddedTable(&source, "flashExpandedFast", "expanded_fast.bin", fastTable.spans)
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return expandedGeneratedData{}, err
	}
	return expandedGeneratedData{source: formatted, long: long.data, modern: modernTable.data, fast: fastTable.data}, nil
}

func expandedSourceHash() string {
	h := sha256.New()
	h.Write([]byte(flashLong))
	h.Write([]byte{0})
	h.Write([]byte(flashModern))
	h.Write([]byte{0})
	h.Write([]byte(flashFast))
	return fmt.Sprintf("%x", h.Sum(nil))
}

type expandedTable struct {
	data  []byte
	spans [9][6]expandedSpan
}

func buildExpandedTable(m *FlashModel, allowed map[int]bool) expandedTable {
	var table expandedTable
	for i := range m.bodies {
		if m.bodies[i] == nil || (allowed != nil && !allowed[i]) {
			continue
		}
		for j := range m.bodies[i].fel {
			e := &m.bodies[i].fel[j]
			if len(e.cnt) == 0 {
				continue
			}
			args := make([]uint16, e.cnt[0])
			e.readArgs(args)
			span := &table.spans[i][j]
			span.argsOffset = uint32(len(table.data))
			span.argsCount = uint32(len(args))
			for _, arg := range args {
				var b [2]byte
				binary.LittleEndian.PutUint16(b[:], arg)
				table.data = append(table.data, b[:]...)
			}
			for len(table.data)%8 != 0 {
				table.data = append(table.data, 0)
			}
			coef := expandedCoefficients(e)
			span.coefOffset = uint32(len(table.data))
			span.coefCount = uint32(len(coef))
			for _, value := range coef {
				var b [8]byte
				binary.LittleEndian.PutUint64(b[:], math.Float64bits(value))
				table.data = append(table.data, b[:]...)
			}
		}
	}
	return table
}

func writeEmbeddedTable(out *bytes.Buffer, name, file string, spans [9][6]expandedSpan) {
	fmt.Fprintf(out, "//go:embed %s\nvar %s string\n\n", file, name)
	fmt.Fprintf(out, "var %sSpans = [9][6]expandedSpan{\n", name)
	for i := range spans {
		wrote := false
		for j := range spans[i] {
			if spans[i][j].coefCount != 0 {
				if !wrote {
					fmt.Fprintf(out, "\t%d: {\n", i)
					wrote = true
				}
				span := spans[i][j]
				fmt.Fprintf(out, "\t\t%d: {argsOffset: %d, argsCount: %d, coefOffset: %d, coefCount: %d},\n", j, span.argsOffset, span.argsCount, span.coefOffset, span.coefCount)
			}
		}
		if wrote {
			fmt.Fprintln(out, "\t},")
		}
	}
	fmt.Fprintln(out, "}")
}

func expandedCoefficients(e *flashElement) []float64 {
	count := 0
	for _, n := range e.cnt {
		count += int(n)
	}
	out := make([]float64, 0, 2*count)
	if e.packed {
		br := &strBits{s: e.src, p: e.coefPos}
		width := 0
		for _, n := range e.cnt {
			for i := int32(0); i < n; i++ {
				width += unzigzag(br.gamma())
				out = append(out, br.coef(width, e.step), br.coef(width, e.step))
			}
		}
		return out
	}
	cos := make([]float64, 0, count)
	sin := make([]float64, 0, count)
	for d, n := range e.cnt {
		rc := &strReader{s: e.src, p: int(e.blocks[2*d])}
		rs := &strReader{s: e.src, p: int(e.blocks[2*d+1])}
		for i := int32(0); i < n; i++ {
			cos = append(cos, float64(float64(rc.zvar())*e.step))
			sin = append(sin, float64(float64(rs.zvar())*e.step))
		}
	}
	for i := range cos {
		out = append(out, cos[i], sin[i])
	}
	return out
}
